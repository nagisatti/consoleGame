#include "main.h"
#include "item.h"
//*****************************************************************************
// マクロ定義
//*****************************************************************************

//*****************************************************************************
// グローバル変数
//*****************************************************************************
ITEM g_item[ITEM_MAX];	// アイテム構造体配列

//=============================================================================
// 初期化処理
//=============================================================================
void InitializeItem()
{
	memset(&g_item, 0, sizeof(ITEM) * ITEM_MAX);
	vec2 pos = { 6.0f, 5.0f };
	CreateItem(pos, 0);
	pos = { 26.0f, 23.0f };
	CreateItem(pos, 0);
}
//=============================================================================
// 終了処理
//=============================================================================
void FinalizeItem()
{ }
//=============================================================================
// 更新処理
//=============================================================================
void UpdateItem()
{	// 使用中の構造体を全て更新する
	for (int cnt = 0; cnt < ITEM_MAX; cnt++)
	{
		// 構造体が未使用なら別の配列を探す
		if ( ! g_item[cnt].use)
		{
			continue;
		}
		// 何か処理があれば書く
	}
}
//=============================================================================
// 描画処理
//=============================================================================
void DrawItem()
{	// 使用中の構造体を全て描画する
	for (int cnt = 0; cnt < ITEM_MAX; cnt++)
	{
		// 構造体が未使用なら別の配列を探す
		if ( ! g_item[cnt].use)
		{
			continue;
		}
		gotoxy(g_item[cnt].pos.x, g_item[cnt].pos.y);	
		textcolor(YELLOW);	//色替え
		printf("＄");
		textcolor(WHITE);	//色替え
	}
}
//=============================================================================
// 生成処理
//=============================================================================
void CreateItem(vec2 pos, int type)
{	// 生成可能な配列を探す
	for (int cnt = 0; cnt < ITEM_MAX; cnt++)
	{
		// 構造体が使用中なら別の配列を探す
		if (g_item[cnt].use)
		{
			continue;
		}
		g_item[cnt].pos.x = pos.x;
		g_item[cnt].pos.y = pos.y;
		g_item[cnt].use = true;
		break;					//アイテムを1つ作成したら終了
	}
}
//=============================================================================
// 消去処理
//=============================================================================
void RemoveItem(int num)
{
	g_item[num].use = false;
}
//=============================================================================
// 構造体情報取得
//=============================================================================
ITEM* GetItem()
{// アイテムの構造体配列の先頭のポインターを返す
	return	&g_item[0];
}
//=============================================================================
// 構造体情報取得
//=============================================================================
ITEM* GetItemSelect(int num)
{// アイテムの構造体配列の指定のポインターを返す
	return	&g_item[num];
}