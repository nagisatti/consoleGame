// ■ポイント
//	- main.h では CONIOEX を定義して「使う側」と宣言しました。
//	- 実体側ではいったん #undef してから conioex.h をインクルードすることで、
//	 conioex.h が「本体の定義（関数の中身）」をここに生成します。
//	- ODR（一意定義ルール）に従い、プロジェクト内で“この1ファイルだけ”が実体を持ちます。

// 使い方:
// - 利用側のソース（main.h など）では #define CONIOEX を立ててから conioex.h を
//	インクルードすると、宣言のみが提供されます。
// - 実体生成側（このファイル）では一旦 #undef CONIOEX してから conioex.h を
//	インクルードすることで、関数本体をここ 1 箇所にだけ生成します。
// - ODR（一意定義ルール）対策：実体生成はこのファイルのみ。
//=============================================================================

/* --------------------------------------------------------------------------
 * 【超詳細】ここでのみ CONIOEX の“関数実体”を生成する理由
 *
 * - 上位（利用側の .cpp）では #define CONIOEX を立てて conioex.h を読むため、
 *	関数は「宣言」だけが見える状態になる。
 * - ここでは #undef CONIOEX でそのフラグを外し、conioex.h を include する。
 *	→ ヘッダ内の #ifdef / #else により、このファイル“だけ”が実体を生成する。
 * - ODR違反（複数翻訳単位での実体重複）を防ぐための仕掛け。
 * -------------------------------------------------------------------------- */

//=============================================================================
#ifdef CONIOEX
#undef CONIOEX
#endif
#include "conioex.h"
