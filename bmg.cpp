#include "main.h"
#include "bgm.h"

//****************************************************************************
//　グローバル変数
//****************************************************************************
static unsigned long long g_bgmSound = 0;



void InitializeBGM()
{
	g_bgmSound = opensound((char*)"sound/mizunishizumupiano.mp3");

	playsound(g_bgmSound,1);
}


void FinalizeBGM()
{
	if (g_bgmSound != 0)
	{
		closesound(g_bgmSound);
	}
}